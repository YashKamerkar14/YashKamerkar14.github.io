import { test, expect } from "@playwright/test";

test("the robot desk stays in its gutter while scrolling, pauses, and restores dialog focus", async ({page}) => {
  await page.setViewportSize({width:1440,height:1000});
  await page.goto("/");
  const desk=page.locator(".robot-dock");
  await expect(desk).toBeHidden();
  await expect(page.locator(".hero-workshop .agent-character:visible")).toHaveCount(1);
  await expect(page.locator(".character-scribe")).toBeHidden();
  const connection=page.getByRole("button",{name:"Backend ↔ Applied AI"});
  const explanation=page.getByRole("tooltip");
  await expect(explanation).toBeHidden();
  await connection.hover();
  await expect(explanation).toContainText("Reliable backend services");
  await expect(explanation).toBeVisible();
  await connection.focus();
  await page.keyboard.press("Enter");
  await expect(connection).toHaveAttribute("aria-expanded","true");
  await page.keyboard.press("Enter");
  await page.keyboard.press("Escape");
  await expect(connection).toHaveAttribute("aria-expanded","false");
  const heroPause=page.locator(".hero-workshop .robot-motion-toggle");
  await heroPause.click();
  await expect(page.locator(".paper-studio")).toHaveAttribute("data-robots-paused","true");
  await expect(page.locator(".scout-walker .agent-eyes")).toHaveCSS("animation-play-state","paused");
  await heroPause.click();
  await page.locator("#experience").evaluate(el=>el.scrollIntoView({behavior:"instant"}));
  await expect(desk).toBeVisible();
  const first=await desk.boundingBox();
  const content=await page.locator("#experience").boundingBox();
  expect(first!.x).toBeGreaterThan(content!.x+content!.width);
  await page.mouse.wheel(0,400);
  await expect.poll(()=>page.evaluate(()=>scrollY)).toBeGreaterThan(1000);
  const second=await desk.boundingBox();
  expect(second!.x).toBe(first!.x);
  expect(second!.y).toBe(first!.y);
  await desk.getByRole("button",{name:"Pause robot animation"}).click();
  await expect(desk.getByRole("button",{name:"Resume robot animation"})).toHaveAttribute("aria-pressed","true");
  const launch=desk.getByRole("button",{name:"Open robot help desk"});
  await launch.click();
  await expect(page.getByRole("dialog",{name:/Small team/})).toBeVisible();
  await expect(page.locator(".agent-team .character-scribe")).toBeVisible();
  await expect(desk).toBeHidden();
  await page.keyboard.press("Escape");
  await expect(launch).toBeFocused();
  await page.setViewportSize({width:1280,height:900});
  await expect(desk).toHaveCSS("display","none");
});

test("phone robots stay inline and reduced motion stops their animations", async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({reducedMotion:"reduce"});
  await page.goto("/");
  await expect(page.locator(".robot-dock")).toHaveCSS("display","none");
  const launch=page.getByRole("button",{name:"Meet Scout and Scribe, the project AI agents"});
  await expect(launch).toBeVisible();
  await expect(page.locator(".scout-walker .agent-eyes")).toHaveCSS("animation-name","none");
  const bounds=await launch.boundingBox();
  const experience=await page.locator("#experience").boundingBox();
  expect(bounds!.y+bounds!.height).toBeLessThan(experience!.y);
  await launch.click();
  await expect(page.getByRole("dialog",{name:/Small team/})).toBeVisible();
  await page.keyboard.press("Escape");
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
});
